// Framework chrome catalogs for app-owned locales (sk-SK, cs-CZ). See .claude/skills/i18n-sync.
//   node scripts/i18n-chrome.mjs extract <dir>              English source chunks → <dir>/*.en.json
//   node scripts/i18n-chrome.mjs validate <en.json> <out.json>  key, plural and placeholder parity
//   node scripts/i18n-chrome.mjs assemble <dir> <locale>    <dir>/*.<locale>.json → app/i18n/<locale>.chrome.ts
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const [command, ...args] = process.argv.slice(2);
const PKG = path.resolve(import.meta.dirname, "../node_modules/@agent-native");
const CHUNKS = {
  "toolkit.a": ["settingsShell"],
  "toolkit.b": ["settings", "settingsModel", "settingsInfra", "settingsOrg", "settingsResources", "settingsApiKeys", "settingsSubAgents"],
  "toolkit.c": ["mcpIntegrations", "observability", "share", "contextXray"],
};
const PLURAL = ["_one", "_few", "_many", "_other"];

const flatten = (messages, prefix = "", into = {}) => {
  for (const [key, value] of Object.entries(messages)) {
    if (typeof value === "string") into[prefix + key] = value;
    else flatten(value, `${prefix}${key}.`, into);
  }
  return into;
};
const read = (file) => JSON.parse(fs.readFileSync(file, "utf8"));
const write = (file, data) => fs.writeFileSync(file, JSON.stringify(data, null, 1));
const placeholders = (text) =>
  [...String(text).matchAll(/\{\{?\s*[\w.]+\s*\}?\}/g)].map((m) => m[0].replace(/\s/g, "")).sort().join(",");

async function extract(dir) {
  fs.mkdirSync(dir, { recursive: true });
  const toolkit = (await import(`${PKG}/toolkit/dist/app/i18n/catalogs/en-US.js`)).default;
  const chunks = Object.fromEntries([...Object.keys(CHUNKS), "toolkit.d"].map((name) => [name, {}]));
  for (const [key, value] of Object.entries(toolkit)) {
    const prefix = key.split(".")[0];
    const name = Object.keys(CHUNKS).find((chunk) => CHUNKS[chunk].includes(prefix)) ?? "toolkit.d";
    chunks[name][key] = value;
  }
  // Core messages: the framework translates only the supplemental set for its
  // own locales; add the core-only keys that toolkit and app components read.
  const { loadCoreMessagesForLocale } = await import(`${PKG}/core/dist/localization/core-messages.js`);
  const core = flatten(await loadCoreMessagesForLocale("en-US"));
  const coreAll = flatten((await import(`${PKG}/core/dist/localization/default-messages.js`)).default);
  const toolkitKeys = new Set(Object.keys(toolkit).map((key) => `agentChat.${key}`));
  const used = new Set(
    execSync(`rg -oN --no-filename '\\bt\\("[a-zA-Z][\\w.]+"' "${PKG}/toolkit/dist" "${PKG}/core/dist/client" app -g '*.js' -g '*.tsx' -g '*.ts' | sort -u`)
      .toString().trim().split("\n").map((line) => line.slice(3, -1)),
  );
  for (const [key, value] of Object.entries(coreAll)) {
    if (toolkitKeys.has(key)) continue;
    if (used.has(key) || used.has(key.replace(/_(one|other)$/, ""))) core[key] = value;
  }
  chunks.core = core;
  for (const [name, chunk] of Object.entries(chunks)) {
    write(path.join(dir, `${name}.en.json`), chunk);
    console.log(name, Object.keys(chunk).length);
  }
}

function validate(enFile, outFile) {
  const [en, out] = [read(enFile), read(outFile)];
  const expected = new Set(
    Object.keys(en).flatMap((key) =>
      key.endsWith("_one") ? PLURAL.map((s) => key.slice(0, -4) + s) : key.endsWith("_other") ? [] : [key],
    ),
  );
  const problems = [];
  for (const key of expected) {
    const src = en[key] ?? en[key.replace(/_(few|many)$/, "_other")];
    if (!(key in out)) problems.push(`missing: ${key}`);
    else if (typeof out[key] !== "string" || !out[key].trim()) problems.push(`empty: ${key}`);
    else if (placeholders(src) !== placeholders(out[key])) problems.push(`placeholders differ: ${key}`);
    else if (out[key] === src && src.length > 3 && !/^[A-Z][a-zA-Z]*$|^[\w.-]+$/.test(src)) problems.push(`untranslated?: ${key} = ${JSON.stringify(src)}`);
  }
  for (const key of Object.keys(out)) if (!expected.has(key)) problems.push(`extra: ${key}`);
  console.log(problems.length ? problems.join("\n") : "OK");
  process.exit(problems.length ? 1 : 0);
}

function assemble(dir, locale) {
  const toolkit = Object.assign({}, ...["a", "b", "c", "d"].map((c) => read(path.join(dir, `toolkit.${c}.${locale}.json`))));
  const core = read(path.join(dir, `core.${locale}.json`));
  const file = path.resolve(import.meta.dirname, "../app/i18n", `${locale}.chrome.ts`);
  fs.writeFileSync(
    file,
    `// Generated by scripts/i18n-chrome.mjs from the installed @agent-native catalogs; see .claude/skills/i18n-sync.
// toolkit: flat keys of @agent-native/toolkit/dist/app/i18n/catalogs/en-US.js, nested under agentChat at load.
// core: core messages the toolkit and app read, overriding the English fallback.
const messages = ${JSON.stringify({ toolkit, core }, null, 2)};

export default messages;
`,
  );
  console.log(file, "toolkit", Object.keys(toolkit).length, "core", Object.keys(core).length);
}

if (command === "extract") await extract(args[0]);
else if (command === "validate") validate(args[0], args[1]);
else if (command === "assemble") assemble(args[0], args[1]);
else { console.error("usage: extract <dir> | validate <en.json> <out.json> | assemble <dir> <locale>"); process.exit(1); }
